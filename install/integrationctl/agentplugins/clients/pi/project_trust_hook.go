package pi

// piTrustHookMarker starts every generated hook revision. Only a file with
// this marker may be replaced; any other bytes at the reserved path are
// foreign and preserved.
const piTrustHookMarker = "// Generated by Universal Agent Plugins: Pi project trust hook"

// piTrustHookSource is the complete, deterministic user extension. It uses
// only syntax that is both TypeScript and plain ECMAScript, so Pi loads it as
// index.ts and tests can execute the identical bytes with Node.
//
// Pi consults user extensions first, so the hook defers whenever Pi already
// owns the decision: a saved trust.json entry for the folder or an ancestor,
// or a defaultProjectTrust of "always" or "never". It answers "yes" only for a
// recorded project whose .pi holds UAP-managed names alone and whose ancestors
// expose no .agents/skills. It never asks Pi to remember the answer.
const piTrustHookSource = piTrustHookMarker + `, schema 1.
// Answers "yes" only for a project recorded by a confirmed UAP installation
// whose .pi holds nothing but UAP-managed resources, when Pi has no saved
// decision or non-default policy for it. Everything else, including any
// error, stays "undecided" so Pi's own trust flow decides.
import { lstatSync, readdirSync, readFileSync, realpathSync } from "node:fs";
import { homedir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const LIMIT = 4194304;
const SURFACES = ["extensions", "skills", "prompts", "themes"];
const ENTRIES = new Set([...SURFACES, "mcp.json", "mcp.json.agentplugins.lock"]);
const OWNED = ["extensions", "skills", "prompts", "themes", "mcp_servers"];

function comparable(path) {
  const full = resolve(path);
  return process.platform === "win32" ? full.toLowerCase() : full;
}

function kind(path) {
  try {
    const info = lstatSync(path);
    return info.isDirectory() ? "directory" : info.isFile() ? "file" : "other";
  } catch (error) {
    if (error && error.code === "ENOENT") return "absent";
    throw error;
  }
}

function object(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function document(path, absent) {
  const found = kind(path);
  if (found === "absent" && absent !== undefined) return absent;
  if (found !== "file" || lstatSync(path).size > LIMIT) throw new Error("unexpected trust input");
  const value = JSON.parse(readFileSync(path, "utf8").replace(/^\uFEFF/, ""));
  if (!object(value)) throw new Error("unexpected trust input");
  return value;
}

function owned(config, owners) {
  const names = Object.fromEntries(OWNED.map((surface) => [surface, new Set()]));
  for (const [artifact, entry] of Object.entries(owners)) {
    if (!object(entry)) throw new Error("invalid owner");
    // A removed installation leaves no live package directory to vouch for.
    if (kind(join(config, "extensions", artifact)) !== "directory") continue;
    for (const surface of OWNED) {
      const list = entry[surface] ?? [];
      if (!Array.isArray(list) || list.some((name) => typeof name !== "string")) throw new Error("invalid owner");
      for (const name of list) names[surface].add(name);
    }
  }
  return names;
}

function onlyOwned(project, owners) {
  const config = join(project, ".pi");
  if (kind(config) !== "directory") return false;
  const names = owned(config, owners);
  if (readdirSync(config).some((name) => !ENTRIES.has(name))) return false;
  for (const surface of SURFACES) {
    const directory = join(config, surface);
    const found = kind(directory);
    if (found === "absent") continue;
    if (found !== "directory") return false;
    for (const name of readdirSync(directory)) {
      if (!names[surface].has(name) || kind(join(directory, name)) !== "directory") return false;
    }
  }
  const mcp = document(join(config, "mcp.json"), {});
  if (Object.keys(mcp).some((key) => key !== "mcpServers")) return false;
  const servers = mcp.mcpServers ?? {};
  if (!object(servers) || Object.keys(servers).some((name) => !names.mcp_servers.has(name))) return false;
  let home = resolve(process.env.HOME || homedir());
  try {
    home = realpathSync(home);
  } catch {}
  const userSkills = comparable(join(home, ".agents", "skills"));
  for (let directory = project; ; directory = dirname(directory)) {
    const skills = join(directory, ".agents", "skills");
    if (comparable(skills) !== userSkills && kind(skills) !== "absent") return false;
    if (dirname(directory) === directory) return true;
  }
}

function leftToHook(agent, project) {
  // A saved trust.json decision or a non-default policy belongs to Pi.
  const settings = document(join(agent, "settings.json"), {});
  if (settings.defaultProjectTrust === "always" || settings.defaultProjectTrust === "never") return false;
  const saved = document(join(agent, "trust.json"), {});
  for (let directory = project; ; directory = dirname(directory)) {
    for (const [path, decision] of Object.entries(saved)) {
      if ((decision === true || decision === false) && comparable(path) === comparable(directory)) return false;
    }
    if (dirname(directory) === directory) return true;
  }
}

function decide(cwd) {
  const hook = dirname(realpathSync(fileURLToPath(import.meta.url)));
  if (basename(hook) !== "agentplugins-project-trust" || basename(dirname(hook)) !== "extensions") return false;
  const recorded = document(join(hook, "projects.json"));
  if (recorded.schema_version !== 1 || !object(recorded.projects)) return false;
  const project = realpathSync(resolve(cwd));
  const matches = Object.entries(recorded.projects).filter(([root]) => comparable(root) === comparable(project));
  if (matches.length !== 1 || !object(matches[0][1])) return false;
  return leftToHook(dirname(dirname(hook)), project) && onlyOwned(project, matches[0][1]);
}

export default function agentPluginsProjectTrust(pi) {
  pi.on("project_trust", (event) => {
    try {
      return { trusted: typeof event?.cwd === "string" && decide(event.cwd) ? "yes" : "undecided" };
    } catch {
      return { trusted: "undecided" };
    }
  });
}
`
