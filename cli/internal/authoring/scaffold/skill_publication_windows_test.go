func TestWindowsSkillCheckedPublicationWithReaderProcess(t *testing.T) {
	for _, existing := range []bool{false, true} {
		for _, kind := range []string{"release", "collision", "cancel", "persistent", "tree", "core", "reservation"} {
			name := kind + "-absent"
			if existing {
				name = kind + "-existing"
			}
			t.Run(name, func(t *testing.T) { testWindowsSkillReaderPublication(t, existing, kind) })
		}
	}
}

func testWindowsSkillReaderPublication(t *testing.T, existing bool, kind string) {
	t.Helper()
	root, plan, gate := skillFixture(t)
	if kind == "reservation" {
		probe := filepath.Join(root, ".authoring-reservation-probe")
		if err := os.WriteFile(probe, nil, 0600); err != nil {
			t.Fatal(err)
		}
		requireRenameRoundTrip(t, probe, probe+"-moved")
		if err := os.Remove(probe); err != nil {
			t.Fatal(err)
		}
	}
	parent, destination := root, filepath.Join(root, "skills")
	if existing {
		parent = destination
		if err := os.Mkdir(parent, 0700); err != nil {
			t.Fatal(err)
		}
		destination = filepath.Join(parent, plan.name)
	}
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	var foreign string
	waits := 0
	blocked := errors.New("reservation mutation denied without changing original")
	var mutationBlocked bool
	ops := applyOps{write: writeTree, rename: renameExclusive}
	ops.publish = func(ctx context.Context, from *os.File, old string, to *os.File, new string, check func() error) error {
		// Exercise the actual ApplySkill guard lifetime, not just its primitive.
		h, err := skillStageReader(filepath.Clean(from.Name()))
		if err == nil {
			_ = windows.CloseHandle(h)
			t.Fatal("production stage guard released before publication")
		}
		if err != windows.STATUS_SHARING_VIOLATION {
			t.Fatalf("unexpected stage reader refusal: %v", err)
		}
		release := holdRenameReader(t, parent)
		defer release()
		r := &renameRetry{ctx: ctx, check: check, budget: time.Second, attempts: 3}
		r.wait = func(ctx context.Context, _ time.Duration) error {
			waits++ // Reached only after the actual commit syscall fails sharing.
			if kind == "persistent" {
				return nil
			}
			release()
			switch kind {
			case "collision":
				if err := os.Mkdir(destination, 0700); err != nil {
					t.Fatal(err)
				}
				foreign = filepath.Join(destination, "foreign")
			case "cancel":
				cancel()
				return ctx.Err()
			case "tree":
				path := filepath.Join(filepath.Clean(from.Name()), old, "SKILL.md")
				if !existing {
					path = filepath.Join(filepath.Clean(from.Name()), old, plan.name, "SKILL.md")
				}
				if err := os.WriteFile(path, []byte("changed generated bytes"), 0600); err != nil {
					t.Fatal(err)
				}
			case "core":
				foreign = filepath.Join(root, "plugin.json")
			case "reservation":
				foreign = filepath.Join(root, skillReservation(plan.name))
				if reservationRenameProtected(t, foreign) {
					foreign, mutationBlocked = "", true
					return blocked
				}
			}
			if foreign != "" {
				if err := os.WriteFile(foreign, []byte("untouched foreign bytes"), 0600); err != nil {
					t.Fatal(err)
				}
			}
			return nil
		}
		return renameResult(from, old, to, new, renameWindows(from, old, to, new, r))
	}
	result, err := applySkill(ctx, plan, root, gate, sharedSkillValidation(plan.name), ops)
	if kind == "release" {
		if err != nil || !result.Committed || waits != 1 {
			t.Fatalf("result=%+v waits=%d err=%v", result, waits, err)
		}
		if body, err := os.ReadFile(result.Destination + "/SKILL.md"); err != nil || string(body) != string(plan.body) {
			t.Fatalf("published bytes: %q %v", body, err)
		}
	} else if err == nil || result.Committed {
		t.Fatalf("unsafe publication: result=%+v waits=%d err=%v", result, waits, err)
	} else if kind == "persistent" {
		if waits != 2 || !errors.Is(err, windows.ERROR_SHARING_VIOLATION) {
			t.Fatalf("exhaustion waits=%d err=%v", waits, err)
		}
	} else if waits != 1 {
		t.Fatalf("expected one failed commit before revalidation: waits=%d err=%v", waits, err)
	}
	if kind == "cancel" && !errors.Is(err, context.Canceled) || mutationBlocked && !errors.Is(err, blocked) {
		t.Fatal(err)
	}
	if foreign != "" {
		if body, e := os.ReadFile(foreign); e != nil || string(body) != "untouched foreign bytes" {
			t.Fatalf("foreign bytes changed: %q %v", body, e)
		}
	}
	parents := []string{root}
	if existing {
		parents = append(parents, parent)
	}
	for _, parent := range parents {
		entries, readErr := os.ReadDir(parent)
		if readErr != nil {
			t.Fatal(readErr)
		}
		for _, entry := range entries {
			path := filepath.Join(parent, entry.Name())
			if strings.HasPrefix(entry.Name(), ".authoring-") && path != foreign && path != foreign+"-moved" {
				t.Fatalf("owned stage or reservation remains: %s", path)
			}
		}
	}
}

func reservationRenameProtected(t *testing.T, path string) bool {
	t.Helper()
	before, err := os.Lstat(path)
	if err != nil {
		t.Fatal(err)
	}
	moved := path + "-moved"
	if err := os.Rename(path, moved); err == nil {
		// The displaced owned reservation remains test-owned, not a foreign
		// replacement, and is removed after Apply has retained its identity.
		t.Cleanup(func() { _ = os.Remove(moved) })
		return false
	} else if !errors.Is(err, windows.ERROR_ACCESS_DENIED) && !errors.Is(err, windows.ERROR_SHARING_VIOLATION) {
		t.Fatal(err)
	}
	after, err := os.Lstat(path)
	body, readErr := os.ReadFile(path)
	if err != nil || !os.SameFile(before, after) || readErr != nil || len(body) != 0 {
		t.Fatalf("blocked reservation mutation changed original: %v %v %q", err, readErr, body)
	}
	if _, err := os.Lstat(moved); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("blocked reservation mutation created destination: %v", err)
	}
	return true
}
