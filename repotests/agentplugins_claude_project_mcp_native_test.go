func claudeProjectRunScriptedForTool(t *testing.T, f *claudeProjectNativeFixture, project, toolName string, wantCall bool) {
	t.Helper()
	model := newClaudeProjectScriptedModel(t)
	model.toolName = toolName
	env := append(f.base.env(filepath.Dir(f.client)),
		"ANTHROPIC_BASE_URL="+model.server.URL,
		"ANTHROPIC_AUTH_TOKEN=uap-disposable-fixture-token",
		"CLAUDE_CODE_DISABLE_1M_CONTEXT=1",
		"ENABLE_TOOL_SEARCH=false",
		// One-shot scripted model requests must see the real stdio tool catalog;
		// extend only Claude's documented first-connection window on slow hosts.
		"MCP_CONNECT_TIMEOUT_MS=20000")
	ctx, cancel := context.WithTimeout(context.Background(), 85*time.Second)
	defer cancel()
	capture := captureProjectNative(ctx, f.client, project, env, []string{
		"-p", "Call the exact uap_ping project MCP tool once if it is available.",
		"--output-format", "stream-json", "--verbose", "--max-turns", "4",
		"--permission-mode", "bypassPermissions", "--model", "claude-sonnet-4-5",
	}, 1<<20, 80*time.Second)
	if capture.Exit != 0 || capture.Error != "" || capture.Deadline || capture.StdoutLimit || capture.StderrLimit {
		t.Fatalf("native Claude project model session failed: exit=%d kind=%s deadline=%t stdout_limit=%t stderr_limit=%t",
			capture.Exit, capture.ErrorKind, capture.Deadline, capture.StdoutLimit, capture.StderrLimit)
	}
	requests, advertised, calls, results, invalid := model.stats()
	if requests == 0 || requests > 8 || invalid != 0 {
		t.Fatalf("unqualified scripted Claude session: requests=%d invalid=%d kinds=%v", requests, invalid, model.invalidSummary())
	}
	if wantCall && (advertised == 0 || calls != 1 || results == 0) {
		t.Fatalf("native Claude failed to dispatch/return exact project MCP tool: advertised=%d calls=%d results=%d", advertised, calls, results)
	}
	if !wantCall && (advertised != 0 || calls != 0 || results != 0) {
		t.Fatalf("foreign project MCP tool leaked into control project: advertised=%d calls=%d results=%d", advertised, calls, results)
	}
}

